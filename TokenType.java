public enum TokenType {
    // Literals
    BOOLEAN_LITERAL,
    INTEGER_LITERAL,
    FLOAT_LITERAL,
    STRING_LITERAL,
    CHAR_LITERAL,
    // Identifiers
    IDENTIFIER,
    
    // Operators
    OPERATOR,
    
    // Punctuators
    PUNCTUATOR,
    
    // Comments
    SINGLE_LINE_COMMENT,
    MULTI_LINE_COMMENT,
    
    // Special
    EOF,

  BOOLEAN_EXPRESSION,

  ERROR

}
